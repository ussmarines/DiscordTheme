const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const entries = [
    ['message-square-text', ['Fils', 'Threads']],
    ['pin', ['Messages épinglés', 'Pinned Messages']],
    ['users-round', ['Masquer la liste des membres', 'Afficher la liste des membres', 'Hide Member List', 'Show Member List']],
];
function mask(name) {
    let svg = fs.readFileSync(path.join(root, 'assets/icons/lucide', `${name}.svg`), 'utf8');
    if (/<script|<foreignObject|<image|href=|onload=|<style/iu.test(svg)) throw new Error(`Unsafe SVG: ${name}`);
    svg = svg.replace(/\s+/gu, ' ').replace('stroke="currentColor"', 'stroke="black"').replace(/ (?:width|height)="24"/gu, '').replace(/> </gu, '><').replace(/ \/>/gu, '/>').trim();
    const encoded = encodeURIComponent(svg).replace(/%20/gu, ' ').replace(/%3D/gu, '=').replace(/%22/gu, "'").replace(/%3A/gu, ':').replace(/%2F/gu, '/').replace(/%2C/gu, ',');
    return `url("data:image/svg+xml,${encoded}") center / contain no-repeat`;
}
let css = '/* Generated by scripts/icons.js from the pinned, licensed Lucide SVGs. */\n';
for (const [name, labels] of entries) {
    const selectors = [`#app-mount .toolbar__9293f :is(${labels.map(label => `[aria-label="${label}"]`).join(',')}) svg`];
    css += `${selectors.join(',\n')} { width: 24px; height: 24px; background: currentColor; mask: ${mask(name)};${name === 'pin' ? ' rotate: 35deg;' : ''} }\n`;
    css += `${selectors.map(s => `${s} > *`).join(',\n')} { opacity: 0; }\n`;
}
const home = "#app-mount .guilds__5e434 [data-list-item-id='guildsnav___home'] .childWrapper__6e9f8 > svg";
css += `${home} { width: 28px; height: 28px; background: currentColor; mask: ${mask('messages-square')}; }\n${home} > * { opacity: 0; }\n`;
const search = '#app-mount .toolbar__9293f .searchBar_c322aa svg';
css += `${search} { background: currentColor; mask: ${mask('search')}; }\n${search} > * { opacity: 0; }\n`;
const voiceIcons = [
    ['video-off', '#app-mount .actionButtons_e131a9 > button:nth-of-type(1) .buttonContents_e131a9'],
    ['video', '#app-mount .actionButtons_e131a9 > button:nth-of-type(1).buttonActive_e131a9 .buttonContents_e131a9'],
    ['screen-share', '#app-mount .actionButtons_e131a9 > button:nth-of-type(2) .buttonContents_e131a9'],
    ['shapes', '#app-mount .actionButtons_e131a9 > button:nth-of-type(3) .buttonContents_e131a9'],
    ['party-popper', '#app-mount .actionButtons_e131a9 [aria-label="Ouvrir Soundboard"] .buttonContents_e131a9'],
];
for (const [name, selector] of voiceIcons) {
    css += `${selector} { width: 20px; height: 20px; flex: 0 0 20px; background: currentColor; mask: ${mask(name)}; }\n`;
    css += `${selector} > * { opacity: 0; }\n`;
}
fs.writeFileSync(path.join(root, 'src/70-icons.css'), css);
